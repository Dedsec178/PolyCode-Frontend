// Generates the four Flutter course data files from the chapter/lesson
// specs in ./lessonData/*.mjs. Run with: node generateCurriculum.mjs
//
// Output files (do not hand-edit — edit the lessonData/*.mjs specs instead):
//   ../data/flutterCurriculum.js
//   ../data/flutterAppVideoLinks.js
//   ../data/flutterAppLessonOutcomes.js
//   ../data/flutterAppSecondQuizzes.js

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { renderChapter } from "./builder.mjs";

import { CH_MEET } from "./lessonData/01-meet.mjs";
import { CH_SETUP } from "./lessonData/02-setup.mjs";
import { CH_DART_BASICS } from "./lessonData/03-dart-basics.mjs";
import { CH_DART_OOP } from "./lessonData/04-dart-oop.mjs";
import { CH_PROJECT_ANATOMY } from "./lessonData/05-project-anatomy.mjs";
import { CH_FIRST_UI } from "./lessonData/06-first-ui.mjs";
import { CH_LAYOUTS } from "./lessonData/07-layouts.mjs";
import { CH_FORMS } from "./lessonData/08-forms.mjs";
import { CH_NAVIGATION } from "./lessonData/09-navigation.mjs";
import { CH_STATE } from "./lessonData/10-state.mjs";
import { CH_LISTS_MODELS } from "./lessonData/11-lists-models.mjs";
import { CH_NETWORKING } from "./lessonData/12-networking.mjs";
import { CH_STORAGE } from "./lessonData/13-storage.mjs";
import { CH_AUTH } from "./lessonData/14-auth.mjs";
import { CH_DEVICE } from "./lessonData/15-device.mjs";
import { CH_POLISH } from "./lessonData/16-polish.mjs";
import { CH_ARCHITECTURE } from "./lessonData/17-architecture.mjs";
import { CH_REALTIME } from "./lessonData/18-realtime.mjs";
import { CH_TESTING } from "./lessonData/19-testing.mjs";
import { CH_PRODUCTION } from "./lessonData/20-production.mjs";
import { CH_ADVANCED } from "./lessonData/21-advanced.mjs";
import { CH_PROJECTS } from "./lessonData/22-projects.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT_DIR = path.resolve(__dirname, "../data");

const CHAPTERS = [
  CH_MEET,
  CH_SETUP,
  CH_DART_BASICS,
  CH_DART_OOP,
  CH_PROJECT_ANATOMY,
  CH_FIRST_UI,
  CH_LAYOUTS,
  CH_FORMS,
  CH_NAVIGATION,
  CH_STATE,
  CH_LISTS_MODELS,
  CH_NETWORKING,
  CH_STORAGE,
  CH_AUTH,
  CH_DEVICE,
  CH_POLISH,
  CH_ARCHITECTURE,
  CH_REALTIME,
  CH_TESTING,
  CH_PRODUCTION,
  CH_ADVANCED,
  CH_PROJECTS,
];

// ── Assign sequential lesson ids: flutter-0, flutter-1, ... ────────────
let counter = 0;
const chapterIdLists = CHAPTERS.map((ch) =>
  ch.lessons.map(() => `flutter-${counter++}`),
);
const TOTAL_LESSONS = counter;

function pad(s) {
  return s;
}

// ── 1) flutterCurriculum.js ─────────────────────────────────────────────
const chapterSources = CHAPTERS.map((ch, i) =>
  renderChapter(ch, chapterIdLists[i]),
).join("\n");

const curriculumSource = `// PolyCode — Flutter Development: Zero to Real Apps
// ${CHAPTERS.length} chapters · ${TOTAL_LESSONS} lessons · Dart/Flutter coding challenges
// AUTO-GENERATED by scripts/generateCurriculum.mjs — edit scripts/lessonData/*.mjs
// and re-run \`node scripts/generateCurriculum.mjs\`, do not hand-edit this file.
// YouTube links: edit flutterAppVideoLinks.js (not this file).

import { applyLessonVideoLinks } from "../../shared/applyLessonVideoLinks";
import { FLUTTER_APP_VIDEO_LINKS } from "./flutterAppVideoLinks";
import { FLUTTER_APP_LESSON_OUTCOMES } from "./flutterAppLessonOutcomes";
import { applySecondQuizzes } from "../../shared/applySecondQuizzes";
import { FLUTTER_APP_SECOND_QUIZZES } from "./flutterAppSecondQuizzes";

function quiz(question, options, answer, explanation) {
  return { type: "quiz", question, options, answer, explanation };
}

function challenge(title, description, starterCode, solutionCode, tests) {
  return { title, description, starterCode, solutionCode, tests };
}

function kw(id, label, hint, pattern) {
  return { id, label, hint, keywords: [{ pattern }] };
}

export const FLUTTER_APP_CHAPTERS = [
${chapterSources}
];

export const FLUTTER_APP_LESSONS = applySecondQuizzes(
  applyLessonVideoLinks(
    FLUTTER_APP_CHAPTERS.flatMap((ch) =>
      ch.lessons.map((l) => ({
        ...l,
        challenge: l.challenge
          ? { ...l.challenge, id: l.challenge.id || l.id }
          : l.challenge,
        outcomes: l.outcomes ?? FLUTTER_APP_LESSON_OUTCOMES[l.id] ?? [],
        chapterId: ch.id,
        chapterTitle: ch.title,
        chapterColor: ch.color,
      })),
    ),
    FLUTTER_APP_VIDEO_LINKS,
  ),
  FLUTTER_APP_SECOND_QUIZZES,
);

export const FLUTTER_APP_TOTAL_XP = FLUTTER_APP_LESSONS.reduce(
  (s, l) => s + l.xp,
  0,
);
`;

fs.writeFileSync(path.join(OUT_DIR, "flutterCurriculum.js"), curriculumSource);

// ── 2) flutterAppVideoLinks.js ──────────────────────────────────────────
const videoLines = CHAPTERS.map((ch, ci) => {
  const header = `  // ── Ch ${ci + 1}: ${ch.title} ${"─".repeat(
    Math.max(2, 60 - ch.title.length),
  )}`;
  const lines = ch.lessons.map((l, li) => {
    const id = chapterIdLists[ci][li];
    return `  ${JSON.stringify(id)}: "", // ${l.title}`;
  });
  return [header, ...lines].join("\n");
}).join("\n\n");

const videoLinksSource = `/**
 * Flutter course — YouTube video links (edit this file only)
 *
 * Paste your YouTube URL for each lesson below.
 * Leave "" if you do not have a video for that lesson yet.
 *
 * Accepted formats:
 *   https://www.youtube.com/watch?v=VIDEO_ID
 *   https://youtu.be/VIDEO_ID
 *   https://www.youtube.com/embed/VIDEO_ID
 *
 * Linked from: flutterCurriculum.js → FLUTTER_APP_LESSONS
 */

export const FLUTTER_APP_VIDEO_LINKS = {
${videoLines}
};
`;

fs.writeFileSync(
  path.join(OUT_DIR, "flutterAppVideoLinks.js"),
  videoLinksSource,
);

// ── 3) flutterAppLessonOutcomes.js ──────────────────────────────────────
const outcomeEntries = CHAPTERS.flatMap((ch, ci) =>
  ch.lessons.map((l, li) => {
    const id = chapterIdLists[ci][li];
    const items = l.outcomes.map((o) => `    ${JSON.stringify(o)},`).join("\n");
    return `  ${JSON.stringify(id)}: [\n${items}\n  ],`;
  }),
).join("\n");

const outcomesSource = `// Plain-English learning outcomes per Flutter lesson (shown at top of theory view).
// AUTO-GENERATED by scripts/generateCurriculum.mjs — edit scripts/lessonData/*.mjs instead.

export const FLUTTER_APP_LESSON_OUTCOMES = {
${outcomeEntries}
};
`;

fs.writeFileSync(
  path.join(OUT_DIR, "flutterAppLessonOutcomes.js"),
  outcomesSource,
);

// ── 4) flutterAppSecondQuizzes.js ───────────────────────────────────────
const quiz2Entries = CHAPTERS.flatMap((ch, ci) =>
  ch.lessons.map((l, li) => {
    const id = chapterIdLists[ci][li];
    const q2 = l.quiz2;
    const options = q2.options
      .map((o) => `      ${JSON.stringify(o)},`)
      .join("\n");
    return `  ${JSON.stringify(id)}: q(
    ${JSON.stringify(q2.q)},
    [
${options}
    ],
    ${q2.answer},
    ${JSON.stringify(q2.explain)},
  ),`;
  }),
).join("\n");

const secondQuizzesSource = `/**
 * Second MCQ (Question 2 of 2) for every Flutter lesson.
 * The lesson UI requires REQUIRED_QUIZ_COUNT = 2; without these, a generic
 * auto-generated quiz is shown instead.
 * AUTO-GENERATED by scripts/generateCurriculum.mjs — edit scripts/lessonData/*.mjs instead.
 */

function q(question, options, answer, explanation) {
  return { type: "quiz", question, options, answer, explanation };
}

export const FLUTTER_APP_SECOND_QUIZZES = {
${quiz2Entries}
};
`;

fs.writeFileSync(
  path.join(OUT_DIR, "flutterAppSecondQuizzes.js"),
  secondQuizzesSource,
);

console.log(`Chapters: ${CHAPTERS.length}`);
console.log(`Lessons:  ${TOTAL_LESSONS}`);
console.log("Wrote 4 files to", OUT_DIR);
